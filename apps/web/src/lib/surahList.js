export const findSurahByNumber = (n) =>
    SURAH_LIST.find((s) => s.number === Number(n));

export const getSurahName = (surah, lang = "ID") => {
    const isEn = String(lang ?? "ID").toUpperCase() === "EN";
    const num = Number(surah?.number || surah?.surah_number || surah?.surah_id);
    const item = num ? findSurahByNumber(num) : null;

    if (isEn) {
        return (
            surah?.translation?.latin_en ||
            item?.name_en ||
            item?.name ||
            surah?.translation?.latin_idn ||
            surah?.slug ||
            ""
        );
    }

    return (
        surah?.translation?.latin_idn ||
        item?.name ||
        surah?.translation?.latin_en ||
        surah?.slug ||
        ""
    );
};

export const getSurahMeaning = (surah, lang = "ID") => {
    const isEn = String(lang ?? "ID").toUpperCase() === "EN";
    const num = Number(surah?.number || surah?.surah_number || surah?.surah_id);
    const item = num ? findSurahByNumber(num) : null;

    if (isEn) {
        return (
            surah?.translation?.en ||
            item?.meaning_en ||
            surah?.translation?.name_translation ||
            ""
        );
    }

    return (
        item?.meaning ||
        surah?.translation?.idn ||
        surah?.translation?.en ||
        ""
    );
};
